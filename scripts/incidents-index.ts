/**
 * The incidents list is one file per case in `incidents/`, so two cases never touch the
 * same line. `incidents.md` carries the generated table between two markers.
 *
 *   tsx scripts/incidents-index.ts            → rewrite the table block in incidents.md
 *   tsx scripts/incidents-index.ts --check    → exit 1 when a case file is malformed
 *
 * Case file: a front matter block with `case`, `source` and `reported_by` (JSON strings),
 * then four sections in this order: What happened, Evidence, A checker should report,
 * The check does NOT establish.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const BEGIN = '<!-- incidents:begin (generated by scripts/incidents-index.ts; do not edit by hand) -->'
export const END = '<!-- incidents:end -->'

const SECTIONS = ['What happened', 'Evidence', 'A checker should report', 'The check does NOT establish'] as const

export interface Incident {
  file: string
  case: string
  source: string
  reportedBy: string
  sections: Record<(typeof SECTIONS)[number], string>
}

/** Parses one case file; returns the incident or a list of problems. */
export function parseIncident(file: string, text: string): { incident?: Incident; problems: string[] } {
  const problems: string[] = []
  const front = /^---\n([\s\S]*?)\n---\n/.exec(text)
  if (!front) return { problems: [`${file}: missing front matter`] }
  const fields: Record<string, string> = {}
  for (const line of front[1]!.split('\n')) {
    const m = /^(case|source|reported_by): (".*")$/.exec(line)
    if (!m) {
      problems.push(`${file}: front matter line is not a key with a JSON string value: ${line.slice(0, 60)}`)
      continue
    }
    try {
      fields[m[1]!] = JSON.parse(m[2]!) as string
    } catch {
      problems.push(`${file}: ${m[1]} is not a valid JSON string`)
    }
  }
  for (const key of ['case', 'source', 'reported_by']) {
    if (!fields[key]?.trim()) problems.push(`${file}: ${key} is missing or empty`)
  }
  const body = text.slice(front[0].length)
  const sections = {} as Record<(typeof SECTIONS)[number], string>
  let cursor = 0
  for (const name of SECTIONS) {
    const heading = `## ${name}\n`
    const at = body.indexOf(heading, cursor)
    if (at < 0) {
      problems.push(`${file}: section "${name}" is missing or out of order`)
      continue
    }
    const start = at + heading.length
    const next = body.indexOf('\n## ', start)
    const content = body.slice(start, next < 0 ? undefined : next).trim()
    if (!content) problems.push(`${file}: section "${name}" is empty`)
    sections[name] = content
    cursor = start
  }
  if (problems.length > 0) return { problems }
  return {
    incident: { file, case: fields.case!, source: fields.source!, reportedBy: fields.reported_by!, sections },
    problems,
  }
}

export function readIncidents(dir = 'incidents'): { incidents: Incident[]; problems: string[] } {
  const incidents: Incident[] = []
  const problems: string[] = []
  const files = readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md').sort()
  for (const file of files) {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*\.md$/.test(file)) problems.push(`${file}: the file name must be lowercase words joined by hyphens`)
    const parsed = parseIncident(file, readFileSync(join(dir, file), 'utf8'))
    problems.push(...parsed.problems)
    if (parsed.incident) incidents.push(parsed.incident)
  }
  return { incidents, problems }
}

/** A literal pipe is written `\|` in a table cell; a backslash right before it is doubled so it is not read as the escape. */
export const escapePipes = (s: string): string => s.replace(/(\\*)\|/g, (_, backslashes: string) => `${backslashes}${backslashes}\\|`)

const cell = (s: string): string => escapePipes(s.replace(/\r?\n+/g, ' ').trim())

/** The table, one row per case, in file-name order. */
export function renderTable(incidents: Incident[]): string {
  const head = '| Case | Source | What happened | Evidence | A checker should report | The check does NOT establish | Reported by |\n| --- | --- | --- | --- | --- | --- | --- |'
  const rows = incidents.map((i) =>
    `| ${[`[${i.case}](incidents/${i.file})`, i.source, ...SECTIONS.map((s) => i.sections[s]), i.reportedBy].map((c, n) => (n === 0 ? escapePipes(c) : cell(c))).join(' | ')} |`,
  )
  return [head, ...rows].join('\n')
}

/** Replaces the block between the markers; throws when a marker is missing. */
export function withTable(doc: string, table: string): string {
  const a = doc.indexOf(BEGIN)
  const b = doc.indexOf(END)
  if (a < 0 || b < a) throw new Error('incidents.md: the begin/end markers are missing or out of order')
  return `${doc.slice(0, a + BEGIN.length)}\n\n${table}\n\n${doc.slice(b)}`
}

function main(): void {
  const check = process.argv.includes('--check')
  const { incidents, problems } = readIncidents()
  if (problems.length > 0) {
    for (const p of problems) console.error(p)
    process.exit(1)
  }
  if (check) {
    console.log(`incidents: ${incidents.length} case files are well formed`)
    return
  }
  const doc = readFileSync('incidents.md', 'utf8')
  writeFileSync('incidents.md', withTable(doc, renderTable(incidents)))
  console.log(`incidents.md: ${incidents.length} rows written`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
