/**
 * Shared building blocks for the self-contained HTML dashboards (v2).
 *
 * Output contract: one standalone .html file — no external assets, no CDNs,
 * no webfonts. All CSS is inline and all charts are inline SVG, so the report
 * works offline and as a CI artifact. v2 adds ONE inline <script> of fixed,
 * hand-written enhancement code (allowed by the CSP via script-src
 * 'unsafe-inline'); the static markup stays fully readable with JS disabled.
 *
 * Security rules that must never regress — this is a trust layer:
 * 1. Every piece of user data rendered into markup goes through esc().
 * 2. User data reaches JavaScript ONLY through the #mdsc-data JSON blob,
 *    serialized with every '<' escaped as its JSON unicode escape, so a
 *    corrupted datum can never close the script tag. Never interpolate data
 *    into JS source.
 * 3. The enhancement script builds tooltip content with textContent only —
 *    data from the blob must never become markup via innerHTML.
 * 4. The payload deliberately excludes free-text fields that may carry URLs
 *    (explanations, references): the self-containment invariant "http(s)
 *    only inside hrefs" must hold over the whole file.
 */

