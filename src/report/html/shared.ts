/**
 * Tool version stamped on reports, read from package.json (no drift).
 * The relative path differs between source (src/report/html/) and bundle
 * (dist/), so all candidates are tried.
 */
function resolveVersion(): string {
  const require = createRequire(import.meta.url)
  for (const candidate of ['../package.json', '../../package.json', '../../../package.json']) {
    try {
      return (require(candidate) as { version: string }).version
    } catch {
      // try the next candidate
    }
  }
  return 'dev'
}
