export const CHART = { width: 920, height: 320, padL: 64, padR: 16, padT: 14, padB: 30 } as const

export function xAt(i: number, n: number): number {
  return CHART.padL + (n <= 1 ? 0.5 : i / (n - 1)) * (CHART.width - CHART.padL - CHART.padR)
}

export function yAt(value: number, min: number, max: number): number {
  const span = max - min
  const t = span === 0 ? 0.5 : (value - min) / span
  return CHART.height - CHART.padB - t * (CHART.height - CHART.padT - CHART.padB)
}

/** Compact axis tick: adapt decimals to the magnitude of the value. */
export function formatTick(value: number): string {
  const abs = Math.abs(value)
  if (abs >= 1000) return value.toFixed(0)
  if (abs >= 1) return value.toFixed(2)
  return value.toPrecision(2)
}

/** Horizontal gridlines with price labels on the left axis. */
export function renderYGridlines(min: number, max: number, ticks = 5): string {
  const lines: string[] = []
  for (let k = 0; k < ticks; k++) {
    const value = ticks <= 1 ? min : min + ((max - min) * k) / (ticks - 1)
    const y = r2(yAt(value, min, max))
    lines.push(
      `<line class="grid" x1="${CHART.padL}" x2="${CHART.width - CHART.padR}" y1="${y}" y2="${y}"/>`,
      `<text class="tick" x="${CHART.padL - 8}" y="${r2(y + 4)}" text-anchor="end">${esc(formatTick(value))}</text>`,
    )
  }
  return lines.join('\n')
}

/** Date labels along the bottom axis, evenly spaced over the plotted points. */
export function renderXTicks(dates: string[], ticks = 6): string {
  const n = dates.length
  if (n === 0) return ''
  const count = Math.min(ticks, n)
  const labels: string[] = []
  for (let k = 0; k < count; k++) {
    const i = count <= 1 ? 0 : Math.round((k * (n - 1)) / (count - 1))
    labels.push(
      `<text class="tick" x="${r2(xAt(i, n))}" y="${CHART.height - CHART.padB + 20}" text-anchor="middle">${esc(dates[i] ?? '')}</text>`,
    )
  }
  return labels.join('\n')
}

/**
 * Transparent rect covering the plot area. Statically inert; the JS measures
 * it to map the mouse x position to the nearest plotted point for tooltips.
 */
export function renderHoverZone(): string {
  return `<rect id="mdsc-hover-zone" x="${CHART.padL}" y="${CHART.padT}" width="${CHART.width - CHART.padL - CHART.padR}" height="${CHART.height - CHART.padT - CHART.padB}" fill="#ffffff" fill-opacity="0"/>`
}

/** Assemble the final document: markup, JSON blob, enhancement script. */
export function page(title: string, body: string, payload: unknown): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${CSP}">
<title>${esc(title)}</title>
<style>
${CSS}
</style>
</head>
<body>
<main>
${body}
</main>
<script type="application/json" id="mdsc-data">${serializePayload(payload)}</script>
<script>
${ENHANCE_JS}
</script>
</body>
</html>
`
}

/**
 * The enhancement layer: fixed code, written once here, never built from
 * user data. It reads the #mdsc-data JSON blob and, when present:
 *  1. wires the severity filter chips to show/hide finding cards,
 *  2. makes chart markers (data-fi) scroll to their finding card,
 *  3. adds a hover tooltip to the price chart (OHLCV, or both closes and
 *     the % gap on compare pages).
 * Tooltip content is built with textContent only — blob data must never
 * become markup. Everything degrades silently when elements are missing.
 * Note: no URLs appear here; the self-containment test forbids http(s)
 * anywhere outside href attributes.
 */
const ENHANCE_JS = `
(function () {
  'use strict'
  var dataNode = document.getElementById('mdsc-data')
  if (!dataNode) return
  var data
  try {
    data = JSON.parse(dataNode.textContent || '{}')
  } catch (err) {
    return
  }

  var filters = document.getElementById('mdsc-filters')
  if (filters) {
    filters.addEventListener('click', function (ev) {
      var target = ev.target
      if (!target || !target.closest) return
      var btn = target.closest('[data-filter]')
      if (!btn) return
      var filter = btn.getAttribute('data-filter')
      var chips = filters.querySelectorAll('[data-filter]')
      for (var i = 0; i < chips.length; i++) chips[i].classList.toggle('active', chips[i] === btn)
      var cards = document.querySelectorAll('.finding-card')
      for (var j = 0; j < cards.length; j++) {
        var show = filter === 'all' || cards[j].getAttribute('data-severity') === filter
        cards[j].style.display = show ? '' : 'none'
      }
    })
  }

  function jumpTo(card) {
    card.scrollIntoView({ behavior: 'smooth', block: 'center' })
    card.classList.add('highlight')
    setTimeout(function () { card.classList.remove('highlight') }, 2400)
  }
  var markers = document.querySelectorAll('[data-fi]')
  for (var m = 0; m < markers.length; m++) {
    markers[m].style.cursor = 'pointer'
    markers[m].addEventListener('click', function () {
      var card = document.getElementById('finding-' + this.getAttribute('data-fi'))
      if (card) jumpTo(card)
    })
  }

  var svg = document.getElementById('mdsc-price-chart')
  var zone = document.getElementById('mdsc-hover-zone')
  var tip = document.getElementById('mdsc-tooltip')
  if (!svg || !zone || !tip) return
  var points = data.type === 'compare' ? data.points : data.bars
  if (!points || points.length === 0) return

  function fmt(v) {
    if (v === undefined || v === null || !isFinite(v)) return '—'
    return String(Math.round(v * 10000) / 10000)
  }

  function linesFor(p) {
    if (data.type === 'compare') {
      var denom = Math.max(p.a, p.b)
      var gap = denom > 0 ? (Math.abs(p.a - p.b) / denom) * 100 : 0
      return [
        p.d,
        data.sources[0] + ' close ' + fmt(p.a),
        data.sources[1] + ' close ' + fmt(p.b),
        'gap ' + gap.toFixed(2) + '%',
      ]
    }
    var lines = [p.d, 'O ' + fmt(p.o) + '  H ' + fmt(p.h), 'L ' + fmt(p.l) + '  C ' + fmt(p.c)]
    if (p.v !== undefined) lines.push('vol ' + fmt(p.v))
    return lines
  }

  svg.addEventListener('mousemove', function (ev) {
    var rect = zone.getBoundingClientRect()
    if (rect.width <= 0) return
    var frac = (ev.clientX - rect.left) / rect.width
    var idx = Math.round(frac * (points.length - 1))
    if (idx < 0) idx = 0
    if (idx >= points.length) idx = points.length - 1
    var lines = linesFor(points[idx])
    tip.textContent = ''
    for (var i = 0; i < lines.length; i++) {
      var div = document.createElement('div')
      div.textContent = lines[i]
      tip.appendChild(div)
    }
    tip.style.left = ev.clientX + 14 + 'px'
    tip.style.top = ev.clientY + 14 + 'px'
    tip.hidden = false
  })
  svg.addEventListener('mouseleave', function () {
    tip.hidden = true
  })
})()
`

